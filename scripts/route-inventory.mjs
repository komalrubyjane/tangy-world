// Builds docs/ROUTES.md: every route in src/App.jsx and src/admin/AdminApp.jsx
// with its component, who may open it, and which E2E suites load it (and
// whether a phone-sized suite does). A route no suite visits is listed as
// "not covered" — it is not claimed to work.
// Run: node scripts/route-inventory.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';

const app = readFileSync('src/App.jsx', 'utf8');
const admin = readFileSync('src/admin/AdminApp.jsx', 'utf8');
const suites = Object.fromEntries(readdirSync('e2e').filter((f) => f.endsWith('.mjs') && !['lib.mjs', 'make-cam.mjs'].includes(f))
  .map((f) => [f.replace('.mjs', ''), readFileSync(`e2e/${f}`, 'utf8').replace(/\$\{BASE\}/g, '').replace(/BASE \+ /g, '')]));
const MOBILE_SUITES = new Set(['mobile', 'responsive', 'routing', 'waitlist', 'enquiries', 'checkout', 'sweep']);

function routes(src, prefix) {
  const out = [];
  const re = /<Route\s+(?:\n\s*)?path="([^"]+)"\s+(?:\n\s*)?element=\{([\s\S]*?)\}\s*\/>/g;
  let m;
  while ((m = re.exec(src))) {
    const [, path, el] = m;
    const full = prefix ? (path === '*' ? `${prefix}/*` : `${prefix}/${path}`) : path;
    const comp = (el.match(/<(?!Guard|ProtectedRoute|ArtistProtectedRoute)([A-Z]\w+)/) || [])[1] || '—';
    let access = 'Public';
    const g = el.match(/<Guard (requires|anyOf)=\{([^}]+)\}/);
    if (g) access = `${g[1] === 'anyOf' ? 'any of ' : ''}${g[2].replace(/P\./g, '').replace(/[[\]]/g, '')}`;
    else if (/ProtectedRoute/.test(el)) access = /ArtistProtectedRoute/.test(el) ? 'Signed-in artist' : 'Signed in';
    else if (prefix) access = 'Console user';
    if (/Navigate to=/.test(el) && comp === 'Navigate') access += ' (redirect)';
    out.push({ path: full, comp: /Navigate to="([^"]+)"/.test(el) ? `→ ${el.match(/Navigate to="([^"]+)"/)[1]}` : comp, access });
  }
  return out;
}
// Artist routes are nested under /artist.
const artistBlock = app.slice(app.indexOf('<Route path="/artist" element={<ArtistLayout />}>'), app.indexOf('</Route>', app.indexOf('<Route path="/artist" element={<ArtistLayout />}>')));
const all = [
  ...routes(app.replace(artistBlock, ''), ''),
  ...routes(artistBlock.replace(/<Route path="\/artist"[^>]*>/, ''), '/artist'),
  { path: '/artist', comp: 'ArtistsDirectoryPage', access: 'Public' },
  ...routes(admin, '/admin-portal').map((r) => ({ ...r, path: r.path.replace('/admin-portal/index', '/admin-portal') })),
];
if (!all.some((r) => r.path === '/admin-portal')) all.push({ path: '/admin-portal', comp: 'DashboardPage', access: 'DASHBOARD' });

// Which suites visit a route: a literal URL in the suite matching the route pattern.
const toRegex = (p) => new RegExp(`^${p.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/:[A-Za-z]+/g, '[^/?#]+').replace(/\*/g, '.*')}$`);
const urlsIn = (src) => [...src.matchAll(/[`'"](\/(?:[A-Za-z0-9_\-.:${}()/]|\$\{[^}]+\})*)(?:\?[^`'"]*)?[`'"]/g)]
  .map((x) => x[1].replace(/\$\{D\(\d+\)\}/g, 'de300000-demo').replace(/\$\{[^}]+\}/g, 'x')).filter((u) => u.length >= 1);
const visited = Object.fromEntries(Object.entries(suites).map(([k, v]) => [k, urlsIn(v)]));

const rows = all.filter((r) => r.path !== '*' && !r.path.endsWith('/*')).map((r) => {
  const rx = toRegex(r.path);
  const by = Object.entries(visited).filter(([, urls]) => urls.some((u) => rx.test(u))).map(([k]) => k);
  return { ...r, by, mobile: by.some((k) => MOBILE_SUITES.has(k)), deep: by.length > 0 };
}).sort((a, b) => a.path.localeCompare(b.path));

const covered = rows.filter((r) => r.deep).length;
const md = [
  '# Tangy World — route inventory',
  '',
  `Generated by \`node scripts/route-inventory.mjs\` from src/App.jsx and src/admin/AdminApp.jsx. ${rows.length} routes; ${covered} are loaded by at least one E2E suite (see e2e/). "Access" is the route guard; every guarded page is also enforced by the database (RLS / RPC permission checks). Catch-all \`*\` routes render the 404 page.`,
  '',
  '| URL | Page / target | Access | E2E suites that load it | Phone-size checked |',
  '| --- | --- | --- | --- | --- |',
  ...rows.map((r) => `| \`${r.path}\` | ${r.comp} | ${r.access} | ${r.by.join(', ') || '**not covered**'} | ${r.mobile ? 'yes' : '—'} |`),
  '',
].join('\n');
mkdirSync('docs', { recursive: true });
writeFileSync('docs/ROUTES.md', md);
console.log(`${rows.length} routes, ${covered} covered by E2E, ${rows.filter((r) => r.mobile).length} checked at phone size → docs/ROUTES.md`);
console.log('Not covered:', rows.filter((r) => !r.deep).map((r) => r.path).join(' '));
