create or replace function is_assigned_to_event(p_event_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select current_role_name() in ('staff', 'admin', 'super_admin') and exists (
    select 1 from event_assignments
    where event_id = p_event_id and assignee_id = auth.uid() and assignee_role = 'staff' and status <> 'declined'
  );
$$;

