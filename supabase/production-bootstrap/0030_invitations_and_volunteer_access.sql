create or replace function guard_crew_application_insert()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_event events%rowtype;
  v_role user_role;
begin
  -- SQL editor / service role (seeds, imports) are trusted.
  if coalesce(auth.role(), '') not in ('authenticated', 'anon') then
    return new;
  end if;

  new.status := 'pending';
  new.reviewed_by := null; new.reviewed_at := null; new.review_notes := null; new.decision_reason := null;

  select role into v_role from profiles where id = new.user_id;
  if new.event_id is null then
    if new.category = 'volunteer' and console_role_rank(v_role) > 0 then
      raise exception 'Choose the session you want to volunteer at.';
    end if;
    return new;
  end if;

  if new.category is distinct from 'volunteer' then
    raise exception 'Only volunteer applications are for a specific session.';
  end if;
  select * into v_event from events where id = new.event_id;
  if v_event.id is null or v_event.status not in ('on-sale', 'sold-out') or v_event.event_date < current_date then
    raise exception 'That session is not open for volunteers.';
  end if;
  if exists (select 1 from event_assignments where event_id = new.event_id and assignee_id = new.user_id
             and assignee_role = 'volunteer' and status <> 'declined') then
    raise exception 'DUPLICATE_APPLICATION: You are already on the volunteer team for this session.';
  end if;
  new.event_interest := v_event.name || ' · ' || to_char(v_event.event_date, 'DD Mon YYYY');
  return new;
end;
$$;

